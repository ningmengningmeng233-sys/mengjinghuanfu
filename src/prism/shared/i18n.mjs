export function resolveLocale(langPref = 'auto', hostNavigatorLang = '') {
  const norm = String(langPref || 'auto').toLowerCase();
  if (norm === 'zh' || norm.startsWith('zh-')) return 'zh';
  if (norm === 'en' || norm.startsWith('en-')) return 'en';
  const nav = String(
    hostNavigatorLang ||
      (typeof navigator !== 'undefined' && navigator.language ? navigator.language : '') ||
      process?.env?.LANG ||
      'zh',
  ).toLowerCase();
  return nav.startsWith('en') ? 'en' : 'zh';
}

const LANG_PREFIX_RE = /^(auto|zh|en|zh-[a-z]+|en-[a-z]+)$/i;

export function t(arg1, arg2 = null, arg3 = 'zh') {
  let key;
  let params;
  let langPref;
  if (typeof arg1 === 'string' && typeof arg2 === 'string' && LANG_PREFIX_RE.test(arg1) && !DICT.zh[arg1] && !DICT.en[arg1]) {
    langPref = arg1;
    key = arg2;
    params = arg3 && typeof arg3 === 'object' ? arg3 : null;
  } else {
    key = arg1;
    params = arg2 && typeof arg2 === 'object' ? arg2 : null;
    langPref = typeof arg3 === 'string' ? arg3 : 'zh';
  }
  const locale = resolveLocale(langPref);
  const table = DICT[locale] || DICT.zh;
  let str = table[key] ?? DICT.zh[key] ?? DICT.en[key] ?? key;
  if (params && typeof params === 'object') {
    str = str.replace(/\{(\w+)\}/g, (_, k) => (params[k] !== undefined ? String(params[k]) : `{${k}}`));
  }
  return str;
}

export function createTranslator(getLang = () => 'zh') {
  return (key, params = null) => t(key, params, typeof getLang === 'function' ? getLang() : getLang);
}
